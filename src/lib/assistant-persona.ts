/**
 * فحص ما إذا كان الرد يحمل دلالة الاعتذار عن الخروج عن التخصص الديني
 */
export function isOutOfScopeReply(reply: string): boolean {
  if (!reply) return false;
  if (reply.includes(OUT_OF_SCOPE_TAG)) return true;
  if (reply.includes('مخصص للأسئلة الدينية')) return true;
  if (reply.includes('خارج نطاق تخصصي')) return true;
  if (reply.includes('خارج نطاق اختصاصي')) return true;
  if (reply.includes('مخصص لخدمة السنة النبوية')) return true;
  if (reply.includes('مخصص للسنة النبوية والأذكار')) return true;
  if (reply.includes('خارج اختصاصي')) return true;
  return false;
}

/**
 * إزالة الوسم الخفي [OUT_OF_SCOPE] من نص الرد المعروض للمستخدم
 */
export function stripOutOfScopeTag(reply: string): string {
  if (!reply) return reply;
  return reply.replace(/\[OUT_OF_SCOPE\]/g, '').trim();
}

function normalizeForCheck(text: string): string {
  return text
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
    .replace(/[إأآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/[ىي]/g, 'ي')
    .toLowerCase();
}

/**
 * فحص استباقي للأسئلة الواضحة الخارجة عن النطاق الديني
 * (كالسياسة المعاصرة، الطبخ، الرياضة، والبرمجة)
 * لحماية الردود الاحتياطية وتأكيد سلامة المنصة
 */
export function isExplicitlyNonReligiousQuery(text: string): boolean {
  if (!text) return false;
  const norm = normalizeForCheck(text);

  // استثناء الأسئلة الشرعية عن هذه الأمور (مثال: ما حكم أكل البيتزا، حكم لعب كرة القدم)
  const isReligiousQuestion = /(حكم|حلال|حرام|يجوز|سنه|شرع|فتوي|اسلام|كفاره|طهاره|صلاه|صيام|زكاه|حج|اجر|اثم)/.test(norm);
  if (isReligiousQuestion) {
    return false;
  }

  // 1. سياسة وشخصيات معاصرة
  const politicalKeywords = [
    'السيسي', 'ترامب', 'بايدن', 'نتنياهو', 'بوتين', 'اردوغان', 'ماكرون', 'محمد بن سلمان', 'الملك سلمان',
    'رئيس الوزراء', 'رئيس الجمهوريه', 'رئيس الدوله', 'الانتخابات', 'الدستور', 'مجلس النواب',
    'البرلمان', 'انقلاب', 'الحرب الروسيه', 'اوكرانيا'
  ];

  // 2. طبخ ووصفات
  const cookingKeywords = [
    'بيتزا', 'البيتزا', 'طريقه عمل', 'مقادير كيك', 'وصفه كيك',
    'طريقه طبخ', 'شاورما', 'برجر', 'معكرونه', 'باستا', 'حلويات', 'عجينه', 'طبخات'
  ];

  // 3. رياضة ومشاهير
  const sportsKeywords = [
    'ميسي', 'رونالدو', 'ريال مدريد', 'برشلونه', 'دوري ابطال', 'كاس العالم', 'مباراه', 'اهداف اليوم',
    'كره القدم', 'الدوري الانجليزي', 'الهلال', 'النصر', 'الاهلي', 'الزمالك'
  ];

  // 4. فن ومسلسلات
  const artKeywords = [
    'مسلسل', 'فيلم', 'اغنيه', 'مطرب', 'ممثل', 'ممثله', 'سينما', 'نتفلكس', 'netflix'
  ];

  // 5. برمجة وتقنية عامة
  const techKeywords = [
    'بايثون', 'جافاسكريبت', 'كود برمجي', 'برمجه موقع', 'python', 'javascript', 'react', 'css', 'html'
  ];

  const allNonReligious = [
    ...politicalKeywords,
    ...cookingKeywords,
    ...sportsKeywords,
    ...artKeywords,
    ...techKeywords,
  ];

  return allNonReligious.some((kw) => norm.includes(normalizeForCheck(kw)));
}
