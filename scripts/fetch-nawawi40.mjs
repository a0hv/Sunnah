async function main() {
  console.log('جاري جلب ملف الأربعين النووية من مستودع GitHub...');
  const res = await fetch(SOURCE_URL);
  if (!res.ok) {
    throw new Error(`فشل الجلب من GitHub: HTTP ${res.status}`);
  }

  const data = await res.json();
  if (!data.hadiths || !Array.isArray(data.hadiths)) {
    throw new Error('صيغة البيانات غير صحيحة، لم يتم العثور على مصفوفة hadiths');
  }

  console.log(`تم جلب ${data.hadiths.length} حديثاً بنجاح.`);

  const formattedHadiths = data.hadiths.map((h, idx) => {
    const id = idx + 1;
    const title = NAWAWI_TITLES[idx] || `الحديث ${id}`;
    const narrator = NARRATORS[idx] || '';
    const source = SOURCES[idx] || '';

    // Clean arabic text from redundant trailing dots
    const cleanText = h.arabic.trim().replace(/\n\s*\.\s*$/, '').trim();

    return {
      id,
      title,
      text: cleanText,
      narrator,
      source,
    };
  });

  const outputPayload = {
    meta: {
      title: 'الأربعون النووية',
      author: 'الإمام يحيى بن شرف النووي رحمه الله (ت ٦٧٦ هـ)',
      description: 'اثنان وأربعون حديثاً نبوياً جامعاً، عليها مدار الدين وأصول الإسلام وقواعد الأحكام ومحاسن الأخلاق.',
      hadithsCount: formattedHadiths.length,
      source: 'https://github.com/AhmedBaset/hadith-json',
      fetchedAt: new Date().toISOString(),
    },
    hadiths: formattedHadiths,
  };

  fs.writeFileSync(OUTPUT_FILE, JSON.stringify(outputPayload, null, 2), 'utf8');
  console.log(`تم حفظ البيانات بنجاح في: ${OUTPUT_FILE}`);
  console.log(`عدد الأحاديث المجهزة: ${formattedHadiths.length}`);
}

main().catch((err) => {
  console.error('خطأ أثناء تشغيل السكربت:', err);
  process.exit(1);
});
